//! Interface language: English, or Portuguese (Portugal). A string is looked up by its English text,
//! so a missing translation shows English instead of nothing. The choice is kept in
//! `<data dir>/lang`.
//!
//! Covered: navigation, page titles and subtitles, the main buttons, status text, the safety and
//! confirmation texts, and the new workshop pages. Data from the car, trouble code descriptions
//! (they come from the shared database in English) and the Help improve page stay English.

use std::sync::atomic::{AtomicBool, Ordering};

static PT: AtomicBool = AtomicBool::new(false);

pub fn is_pt() -> bool {
    PT.load(Ordering::Relaxed)
}

pub fn set_pt(on: bool) {
    PT.store(on, Ordering::Relaxed);
    if let Some(dir) = crate::dtcdb::data_dir() {
        let _ = std::fs::create_dir_all(&dir);
        let _ = std::fs::write(dir.join("lang"), if on { "pt" } else { "en" });
    }
}

pub fn load() {
    let pt = crate::dtcdb::data_dir().and_then(|d| std::fs::read_to_string(d.join("lang")).ok()).is_some_and(|t| t.trim() == "pt");
    PT.store(pt, Ordering::Relaxed);
}

/// `en` in the chosen language.
pub fn tr(en: &'static str) -> &'static str {
    if !is_pt() {
        return en;
    }
    TABLE.iter().find(|(e, _)| *e == en).map_or(en, |(_, p)| p)
}

